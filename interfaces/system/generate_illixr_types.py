"""
generate_system_types.py

Scans include/illixr/data_format/*.hpp via libclang and writes one YAML file
per header into interfaces/system/illixr/data_format/.  These committed
YAML files describe ILLIXR system struct fields in the same schema used by
bridge type YAMLs, allowing the bridge generator to produce correct dict
conversion code for system types without requiring libclang at configure time.

Invocation
----------
  # From CMake (via SystemTypes.cmake):
  python3 generate_system_types.py --source-dir <ILLIXR_ROOT> --output-dir <interfaces/system>

  # Command line (with staleness check):
  python3 generate_system_types.py --source-dir /path/to/ILLIXR --output-dir ./system

  # Force regeneration even if nothing changed:
  python3 generate_system_types.py --source-dir /path/to/ILLIXR --output-dir ./system --force

Staleness
---------
A JSON state file (.system_types_state.json) in the output dir tracks MD5
hashes of all data_format headers.  The scan only runs when at least one
header has changed.

Output format
-------------
One YAML per header, e.g., system/illixr/data_format/combined_pose.yaml:

  # Auto-generated by generate_system_types.py - do not edit manually.
  # Source: include/illixr/data_format/combined_pose.hpp
  namespace: ILLIXR
  structs:
    combined_pose:
      fields:
        x: {type: float}
        y: {type: float}
        time_ns: {type: uint64}
        valid: {type: bool}
    fast_pose:
      base: illixr.data_format.combined_pose
      fields:
        vx: {type: float}

Dotted names follow the directory convention:
  ILLIXR::combined_pose   -> illixr.data_format.combined_pose
  ILLIXR::data_format::pose -> illixr.data_format.pose (sub-namespace preserved)

Eigen type mapping (C++ -> YAML):
  Eigen::Vector3f  -> type: float,  shape: [3]
  Eigen::Vector3d  -> type: double, shape: [3]
  Eigen::Vector4f  -> type: float,  shape: [4]
  Eigen::Quaternionf -> type: float, shape: [4]
  Eigen::Matrix3f  -> type: float,  shape: [3, 3]
  Eigen::Matrix4f  -> type: float,  shape: [4, 4]
  Eigen::Matrix4d  -> type: double, shape: [4, 4]

Unmappable types (custom templates, shared_ptr, etc.) are skipped with a
comment in the YAML.

Usage note: run this script whenever data_format/ headers change, then commit
the updated system/ YAML files.
"""
