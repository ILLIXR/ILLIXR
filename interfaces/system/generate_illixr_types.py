# pylint: disable=too-many-ancestors
class _FlowListDumper(yaml.Dumper):
    """
    Custom YAML dumper that:
    - Renders lists in flow style: [3, 4] instead of block style (- 3\n- 4)
    - Disables aliases (no &id001 / *id001 for repeated objects)
    """
    def represent_sequence(self, tag, sequence, flow_style=None):
        # Always use flow style for sequences
        """Force flow style ``[a, b]`` for all YAML sequences.

        Args:
            tag (str): YAML tag.
            sequence: The sequence to represent.
            flow_style: Ignored; overridden to ``True``.

        Returns:
            yaml.SequenceNode: A flow-style sequence node.
        """
        return super().represent_sequence(tag, sequence, flow_style=True)

    def ignore_aliases(self, data):
        """Disable YAML aliases so repeated objects are always written in full.

        Args:
            data: Object being considered for aliasing.

        Returns:
            bool: Always ``True``.
        """
        return True


