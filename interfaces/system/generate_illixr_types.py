# Main
# ---------------------------------------------------------------------------


def run(source_dir: Path, output_dir: Path, force: bool = False) -> None:
    """Scan data_format headers and write system type YAML files.

    Only runs when headers have changed (MD5 staleness check) unless ``force=True``.

    Args:
        source_dir (Path): ILLIXR repository root.
        output_dir (Path): Directory to write YAML files into.
        force (bool): Regenerate all YAMLs even if unchanged. Defaults to ``False``.

    Returns:
        None
    """
    # pylint: disable=too-many-locals
    data_format_dir = source_dir / "include" / "illixr" / "data_format"
    include_root = source_dir / "include"

    if not data_format_dir.exists():
        print(f"data_format directory not found: {data_format_dir}", file=sys.stderr)
        sys.exit(1)

    out_dir = output_dir / "illixr" / "data_format"
    state_file = output_dir / ".system_types_state.json"
    state = _load_state(state_file)

    if not force and not _headers_stale(data_format_dir, state):
        print("System types up to date - nothing to do.", file=sys.stderr)
        return

    print("Scanning data_format headers...", file=sys.stderr)
    out_dir.mkdir(parents=True, exist_ok=True)

    headers = sorted(
        h for h in data_format_dir.rglob("*.hpp")
        if "serialization" not in h.parts
        )

    # First pass: collect all struct names across all headers so base class
    # lookups work even when the base is defined in a different header.
    all_struct_names: set[str] = set()
    index = _clang.Index.create()
    for hdr in headers:
        tu = index.parse(
            str(hdr),
            args=["-std=c++17", "-x", "c++",
                  "-I", str(include_root), "-undef"],
            options=(_clang.TranslationUnit.PARSE_SKIP_FUNCTION_BODIES |
                     _clang.TranslationUnit.PARSE_INCOMPLETE),
            )
        for _, sc in _walk_namespace(tu.cursor, [], this_file=hdr):
            all_struct_names.add(sc.spelling)

    # Second pass: full extraction and YAML emission
    for hdr in headers:
        rel = str(hdr.relative_to(source_dir / "include")).replace("\\", "/")
        structs, dependencies = scan_header(hdr, include_root, all_struct_names)
        # Add ref_deps from each struct (KNOWN_ILLIXR_REFS types used as field types)
        for sinfo in structs.values():
            for ref in sinfo.get("ref_deps", []):
                ref_dotted = _KNOWN_ILLIXR_REFS.get(ref, "")
                if ref_dotted and ref_dotted not in dependencies:
                    dependencies.append(f"[system ref] {ref_dotted}")

        yaml_text = emit_header_yaml(structs, rel, dependencies=dependencies)
        # Mirror source subdirectory structure under out_dir
        # e.g. data_format/poses/fast_pose.hpp -> system/illixr/data_format/poses/fast_pose.yaml
        rel_subdir = hdr.relative_to(data_format_dir).parent
        out_subdir = out_dir / rel_subdir
        out_subdir.mkdir(parents=True, exist_ok=True)
        out_file = out_subdir / hdr.with_suffix(".yaml").name
        out_file.write_text(yaml_text)
        n = len(structs)
        rel_out = out_file.relative_to(output_dir)
        print(f"  {hdr.relative_to(data_format_dir.parent)} -> {rel_out}  ({n} struct{'s' if n != 1 else ''})",
              file=sys.stderr)

    # Update state
    _save_state(state_file, {"header_hashes": _current_hashes(data_format_dir)})
    print(f"System type YAMLs written to {out_dir}", file=sys.stderr)


def main() -> None:
    """Parse command-line arguments and invoke ``run()``.

    Returns:
        None
    """
    parser = argparse.ArgumentParser(
        description="Scan ILLIXR data_format headers and write system type YAMLs.")
    parser.add_argument(
        "--source-dir", required=True, type=Path,
        help="ILLIXR repository root (contains include/illixr/data_format/)")
    parser.add_argument(
        "--output-dir", required=True, type=Path,
        help="Directory to write system/ YAML files into (e.g., interfaces/system)")
    parser.add_argument(
        "--force", action="store_true",
        help="Regenerate even if headers have not changed")
    args = parser.parse_args()

    run(args.source_dir, args.output_dir, force=args.force)


if __name__ == "__main__":
    main()
